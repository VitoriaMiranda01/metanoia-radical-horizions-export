-- ============================================================================
-- CLEAN DATABASE SCHEMA MIGRATION SCRIPT
-- ============================================================================
-- This script ensures the database structure is correct and complete.
-- 1. Creates tables if they do not exist.
-- 2. Adds missing columns to existing tables (Idempotent).
-- 3. Creates indexes for performance.
-- 
-- NOTE: This script does NOT insert any data. All tables will remain empty
-- or retain their existing data. You must manually populate configuration
-- tables if they are empty.
-- ============================================================================

-- ============================================================================
-- 1. CONFIGURACOES (Core Configuration)
-- ============================================================================
CREATE TABLE IF NOT EXISTS configuracoes (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    max_equipantes INTEGER DEFAULT 0,
    max_acampantes INTEGER DEFAULT 0,
    edicao_numero INTEGER DEFAULT 0,
    observacoes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- 2. INSCRICOES_STATUS (Global Status Control)
-- ============================================================================
CREATE TABLE IF NOT EXISTS inscricoes_status (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    inscricoes_equipantes BOOLEAN DEFAULT TRUE,
    inscricoes_acampantes BOOLEAN DEFAULT TRUE,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- 3. USERS (Public Profiles / RBAC)
-- ============================================================================
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY REFERENCES auth.users(id),
    email TEXT,
    role TEXT DEFAULT 'user', -- 'organizador', 'equipante', 'acampante', 'parceiro'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

