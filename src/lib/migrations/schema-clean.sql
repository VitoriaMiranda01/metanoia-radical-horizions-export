-- ============================================================================
-- 7. ESCALAS (Team Allocation)
-- ============================================================================
CREATE TABLE IF NOT EXISTS escalas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    equipante_id UUID REFERENCES equipantes(id),
    equipante_nome TEXT,
    area_alocada TEXT,
    is_manual BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

DO $$
BEGIN
    -- Ensure allocation constraint exists
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'escalas_equipante_id_key') THEN
        ALTER TABLE escalas ADD CONSTRAINT escalas_equipante_id_key UNIQUE (equipante_id);
    END IF;
END $$;

